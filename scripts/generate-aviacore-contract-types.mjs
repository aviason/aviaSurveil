#!/usr/bin/env node
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, join, relative, resolve } from 'node:path';

const root = resolve(dirname(new URL(import.meta.url).pathname), '..');
const mirror = join(root, 'integrations/aviacore/contracts');
const catalog = JSON.parse(readFileSync(join(mirror, 'contracts/aviasurveil-production/v3/event-catalog.json'), 'utf8'));
const required = {};
const allowed = {};
const eventSchemas = {};
for (const event of catalog.events) {
  const schema = JSON.parse(readFileSync(join(mirror, event.schema_path), 'utf8'));
  const payload = schema.allOf?.[1]?.properties?.payload;
  required[event.event_type] = payload?.required ?? [];
  allowed[event.event_type] = Object.keys(payload?.properties ?? {});
  eventSchemas[event.event_type] = event.schema_path.split('/').at(-1);
}
function schemaFiles(path, base = path) {
  return readdirSync(path, { withFileTypes: true }).flatMap((entry) => {
    const full = join(path, entry.name);
    return entry.isDirectory() ? schemaFiles(full, base) : [relative(base, full)];
  }).sort();
}
const schemaRoot = join(mirror, 'schemas/events/aviasurveil/v3');
const schemaDocuments = Object.fromEntries(schemaFiles(schemaRoot).map((path) => [path, JSON.parse(readFileSync(join(schemaRoot, path), 'utf8'))]));
const output = join(root, 'apps/api/internal/aviacorecontract/v3/types_generated.go');
mkdirSync(dirname(output), { recursive: true });
const entries = Object.entries(required).sort(([left], [right]) => left.localeCompare(right)).map(([event, fields]) => `\t${JSON.stringify(event)}: {${fields.map((field) => JSON.stringify(field)).join(', ')}},`).join('\n');
const allowedEntries = Object.entries(allowed).sort(([left], [right]) => left.localeCompare(right)).map(([event, fields]) => `\t${JSON.stringify(event)}: {${fields.map((field) => JSON.stringify(field)).join(', ')}},`).join('\n');
const schemaEntries = Object.entries(schemaDocuments).map(([path, schema]) => `\t${JSON.stringify(path)}: ${JSON.stringify(JSON.stringify(schema))},`).join('\n');
const eventSchemaEntries = Object.entries(eventSchemas).sort(([left], [right]) => left.localeCompare(right)).map(([event, schema]) => `\t${JSON.stringify(event)}: ${JSON.stringify(schema)},`).join('\n');
const generated = `// Code generated by scripts/generate-aviacore-contract-types.mjs from the Task 3B contract lock; DO NOT EDIT.\npackage v3\n\nconst ContractVersion = "3.0.0"\n\nvar GeneratedRequiredPayloadFields = map[string][]string{\n${entries}\n}\n\nvar GeneratedAllowedPayloadFields = map[string][]string{\n${allowedEntries}\n}\n\nvar GeneratedEventSchemaByType = map[string]string{\n${eventSchemaEntries}\n}\n\nvar GeneratedSchemaDocuments = map[string]string{\n${schemaEntries}\n}\n`;
const formatted = execFileSync('gofmt', [], { input: generated, encoding: 'utf8' });
if (process.argv.includes('--check')) {
  if (!existsSync(output) || readFileSync(output, 'utf8') !== formatted) throw new Error('Task 3B generated Go types drifted from the locked schemas');
} else {
  mkdirSync(dirname(output), { recursive: true });
  writeFileSync(output, formatted);
}
